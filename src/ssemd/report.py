def _num(value, digits: int = 3) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)) or value == "":
        return "-"
    value = float(value)
    if value == 0:
        return "0"
    if abs(value) >= 100 or abs(value) < 1e-3:
        return f"{value:.{digits - 1}e}".replace("e-0", "e-").replace("e+0", "e")
    return f"{value:.{digits}g}"


def _sigma(row) -> str:
    text = _num(row["sigma300_mS_cm"])
    if row["sigma_kind"] == "upper_bound":
        return f"<= {text}"
    lo, hi = row["sigma300_ci95_lo_mS_cm"], row["sigma300_ci95_hi_mS_cm"]
    if not (isinstance(lo, float) and math.isnan(lo)):
        text += f" ({_num(lo, 2)}-{_num(hi, 2)})"
    return text


def _temps(text) -> str:
    return "/".join(str(text).split(";")) if text else "-"


def _table(header, rows) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


