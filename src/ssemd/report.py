def formula_html(formula: str) -> str:
    """Li10Zn7(PS4)8 -> Li<sub>10</sub>Zn<sub>7</sub>(PS<sub>4</sub>)<sub>8</sub>."""
    import re

    return re.sub(r"(?<=[A-Za-z)])(\d+)", r"<sub>\1</sub>", formula)


def _short(value: float) -> str:
    """Two significant figures, keeping a trailing zero (5.0, 0.96, 15)."""
    rounded = float(f"{value:.2g}")
    if abs(rounded) >= 10:
        return f"{rounded:.0f}"
    if abs(rounded) >= 1:
        return f"{rounded:.1f}"
    return f"{rounded:.2g}"


def readme_table() -> str:
    classes = data.classification()
    fast = classes[classes["class"] == "FAST_VALIDATED"].sort_values("sigma300_mS_cm", ascending=False)
    lines = ["| Composition | σ(300 K) (mS cm<sup>−1</sup>) | E<sub>a</sub> (eV) | Decided by |",
             "|---|---:|---:|---|"]
    for row in fast.to_dict("records"):
        marks = (" †" if "a32_dependent" in row["qualifiers"] else "") + (
            " ‡" if "near_threshold" in row["qualifiers"] else "")
        sigma = _short(row["sigma300_mS_cm"])
        if not math.isnan(row["sigma300_ci95_lo_mS_cm"]):
            sigma += f" ({_short(row['sigma300_ci95_lo_mS_cm'])}–{_short(row['sigma300_ci95_hi_mS_cm'])})"
        decided = README_DECIDED[row["decided_by"]]
        if row["decided_by"] == "six_lead_validation" and row["seeds"] != "0;1;2":
            decided += f" (seeds {row['seeds'].replace(';', ', ')})"
        lines.append(f"| {formula_html(row['formula'])}{marks} | {sigma} | {row['Ea_eV']:.3f} | {decided} |")
    return "\n".join(lines)


def update_readme() -> None:
    readme = paths.REPO / "README.md"
    text = readme.read_text(encoding="utf-8")
    start, end = text.index(README_BEGIN) + len(README_BEGIN), text.index(README_END)
    readme.write_text(text[:start] + "\n" + readme_table() + "\n" + text[end:], encoding="utf-8")


def build() -> list[str]:
    written = []
    update_readme()
    written.append("README.md (fast-conductor table)")
    (paths.DOCS / "results.md").write_text(results_markdown(), encoding="utf-8")
    written.append("docs/results.md")
    try:
        (paths.DOCS / "figures.md").write_text(figures_markdown(), encoding="utf-8")
        written.append("docs/figures.md")
    except ImportError:
        pass
    return written
